package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"regexp"
	"strconv"
	"strings"
)

const goHeader = "// Code generated by tools/gen. DO NOT EDIT.\n\n"

type goGen struct {
	m        *model
	usesJSON bool
	usesTime bool
}

// emitGo 生成 gen/types.go 和 gen/union.go。
func emitGo(m *model) (types, unions []byte, err error) {
	g := &goGen{m: m}
	var body strings.Builder
	for _, name := range sortedKeys(m.types) {
		g.emitNamed(&body, m.types[name])
	}
	var src strings.Builder
	src.WriteString(goHeader)
	src.WriteString("// Package gen 是由 schema/ 生成的类型、常量和数据表（设计文档 C.14、INV-17）。不要手改，改 schema 或 tools/gen 后运行 go run ./tools/gen。\npackage gen\n\n")
	var imps []string
	if g.usesJSON {
		imps = append(imps, `"encoding/json"`)
	}
	if g.usesTime {
		imps = append(imps, `"time"`)
	}
	writeImports(&src, imps)
	src.WriteString(body.String())
	if types, err = formatGo("gen/types.go", src.String()); err != nil {
		return nil, nil, err
	}
	unions, err = formatGo("gen/union.go", g.unionSource())
	return types, unions, err
}

func writeImports(w *strings.Builder, imps []string) {
	switch len(imps) {
	case 0:
	case 1:
		fmt.Fprintf(w, "import %s\n\n", imps[0])
	default:
		w.WriteString("import (\n")
		for _, i := range imps {
			fmt.Fprintf(w, "\t%s\n", i)
		}
		w.WriteString(")\n\n")
	}
}

var goErrLineRe = regexp.MustCompile(`^(\d+):(\d+):`)

// formatGo 用 go/format 格式化；失败时把出错位置附近几行带进错误信息，方便在开发机上看。
func formatGo(name, src string) ([]byte, error) {
	b, err := format.Source([]byte(src))
	if err == nil {
		return b, nil
	}
	msg := err.Error()
	if mm := goErrLineRe.FindStringSubmatch(msg); mm != nil {
		line, _ := strconv.Atoi(mm[1])
		lines := strings.Split(src, "\n")
		for i := max(0, line-3); i < min(len(lines), line+2); i++ {
			msg += fmt.Sprintf("\n    %4d | %s", i+1, lines[i])
		}
	}
	return nil, fmt.Errorf("生成的 %s 不是合法的 Go 代码：%s", name, msg)
}

func goDoc(w *strings.Builder, name, doc, file string) {
	if doc != "" {
		fmt.Fprintf(w, "// %s：%s\n", name, doc)
	} else {
		fmt.Fprintf(w, "// %s 由 schema/%s 生成。\n", name, file)
	}
}

func (g *goGen) emitNamed(w *strings.Builder, n *named) {
	goDoc(w, n.name, n.doc, n.file)
	switch n.kind {
	case kStruct:
		fmt.Fprintf(w, "type %s struct {\n", n.name)
		for _, f := range n.fields {
			if f.doc != "" {
				fmt.Fprintf(w, "\t// %s\n", f.doc)
			}
			tag := f.json
			if !f.required {
				tag += ",omitempty"
			}
			fmt.Fprintf(w, "\t%s %s `json:%q`\n", f.goName, g.fieldType(f), tag)
		}
		w.WriteString("}\n\n")
		g.emitDefaults(w, n)
	case kOpenMap:
		g.usesJSON = true
		fmt.Fprintf(w, "type %s map[string]json.RawMessage\n\n", n.name)
	case kMap:
		fmt.Fprintf(w, "type %s map[string]%s\n\n", n.name, g.expr(n.elem))
	case kArray:
		fmt.Fprintf(w, "type %s []%s\n\n", n.name, g.expr(n.elem))
	case kString:
		fmt.Fprintf(w, "type %s string\n\n", n.name)
	case kInt:
		fmt.Fprintf(w, "type %s int64\n\n", n.name)
	case kNumber:
		fmt.Fprintf(w, "type %s float64\n\n", n.name)
	case kBool:
		fmt.Fprintf(w, "type %s bool\n\n", n.name)
	case kRaw, kStrOrNum:
		g.usesJSON = true
		fmt.Fprintf(w, "type %s = json.RawMessage\n\n", n.name)
	case kTimestamp:
		g.usesJSON, g.usesTime = true, true
		fmt.Fprintf(w, `type %[1]s struct{ time.Time }

const timestampLayout = "2006-01-02T15:04:05.000Z"

// MarshalJSON 输出 UTC、带毫秒（C.01-R7、C.14 §3）。
func (t %[1]s) MarshalJSON() ([]byte, error) {
	return []byte(%[2]q + t.UTC().Format(timestampLayout) + %[2]q), nil
}

// UnmarshalJSON 接受 RFC 3339，转成 UTC。
func (t *%[1]s) UnmarshalJSON(b []byte) error {
	var s string
	if err := json.Unmarshal(b, &s); err != nil {
		return err
	}
	v, err := time.Parse(time.RFC3339Nano, s)
	if err != nil {
		return err
	}
	t.Time = v.UTC()
	return nil
}

`, n.name, `"`)
	case kWholeUnion:
		g.usesJSON = true
		d := goName(n.union.disc)
		fmt.Fprintf(w, "type %s struct {\n\t// %s 是判别字段 %s 的值。\n\t%s %s\n\t// Raw 是整个对象的原文；用 Decode 按 %s 解出具体结构（C.14-R2）。\n\tRaw json.RawMessage\n}\n\n",
			n.name, d, n.union.disc, d, n.union.discType, d)
	}
}

// fieldType：可选字段和可空字段一律指针，json.RawMessage 除外（C.14 §3）。
func (g *goGen) fieldType(f *field) string {
	if f.unionField {
		g.usesJSON = true
		return "json.RawMessage"
	}
	e := g.expr(f.t)
	if k := g.m.kindOf(f.t); k == kRaw || k == kStrOrNum {
		return e
	}
	if !f.required || f.nullable {
		return "*" + e
	}
	return e
}

func (g *goGen) expr(t *typeRef) string {
	if t.name != "" {
		return t.name
	}
	switch t.kind {
	case kString:
		return "string"
	case kInt:
		return "int64"
	case kNumber:
		return "float64"
	case kBool:
		return "bool"
	case kOpenMap:
		g.usesJSON = true
		return "map[string]json.RawMessage"
	case kArray:
		return "[]" + g.expr(t.elem)
	case kMap:
		return "map[string]" + g.expr(t.elem)
	}
	g.usesJSON = true
	return "json.RawMessage"
}

// defaultLit 是标量默认值在 Go 和 TS 里的写法；字段类型不是对应的标量时返回空串。
func defaultLit(k kind, def any) string {
	switch d := def.(type) {
	case string:
		if k == kString {
			return strconv.Quote(d)
		}
	case bool:
		if k == kBool {
			return strconv.FormatBool(d)
		}
	case json.Number:
		if k == kInt || k == kNumber {
			return d.String()
		}
	}
	return ""
}

func (g *goGen) emitDefaults(w *strings.Builder, n *named) {
	var body strings.Builder
	for _, f := range n.fields {
		if f.def == nil || f.required || f.unionField {
			continue
		}
		lit := defaultLit(g.m.kindOf(f.t), f.def)
		if lit == "" {
			continue
		}
		fmt.Fprintf(&body, "\tif v.%s == nil {\n\t\td := %s(%s)\n\t\tv.%s = &d\n\t}\n", f.goName, g.expr(f.t), lit, f.goName)
	}
	if body.Len() == 0 {
		return
	}
	fmt.Fprintf(w, "// ApplyDefaults 把没填的可选字段设为 schema 的默认值（C.14 §3）。\nfunc (v *%s) ApplyDefaults() {\n%s}\n\n", n.name, body.String())
}

// unionSource 是 gen/union.go：DecodeAs 和每个判别联合的解码（C.14-R2）。
func (g *goGen) unionSource() string {
	var w strings.Builder
	w.WriteString(goHeader)
	w.WriteString("package gen\n\n")
	var names []string
	for _, name := range sortedKeys(g.m.types) {
		if g.m.types[name].union != nil {
			names = append(names, name)
		}
	}
	imps := []string{`"bytes"`, `"encoding/json"`}
	if len(names) > 0 {
		imps = append(imps, `"fmt"`)
	}
	writeImports(&w, imps)
	w.WriteString(`// DecodeAs 严格解码一段 JSON：不认识的字段报错（C.14-R2）。
func DecodeAs[T any](raw json.RawMessage) (*T, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	v := new(T)
	if err := dec.Decode(v); err != nil {
		return nil, err
	}
	return v, nil
}

`)
	for _, name := range names {
		n := g.m.types[name]
		u := n.union
		d := goName(u.disc)
		if n.kind == kWholeUnion {
			fmt.Fprintf(&w, `// MarshalJSON 原样输出 Raw（C.14-R2）。
func (v %[1]s) MarshalJSON() ([]byte, error) {
	if len(v.Raw) == 0 {
		return []byte("null"), nil
	}
	return v.Raw, nil
}

// UnmarshalJSON 保存原文，并读出 %[3]s。
func (v *%[1]s) UnmarshalJSON(b []byte) error {
	var head struct {
		%[2]s %[4]s `+"`json:%[5]q`"+`
	}
	if err := json.Unmarshal(b, &head); err != nil {
		return err
	}
	v.%[2]s = head.%[2]s
	v.Raw = append(json.RawMessage(nil), b...)
	return nil
}

// Decode 按 %[3]s 解出整个对象（C.14-R2）。
func (v *%[1]s) Decode() (any, error) {
	switch v.%[2]s {
`, name, d, u.disc, u.discType, u.disc)
			for _, b := range u.branches {
				fmt.Fprintf(&w, "\tcase %q:\n\t\treturn DecodeAs[%s](v.Raw)\n", b.value, b.typ)
			}
		} else {
			f := goName(u.field)
			fmt.Fprintf(&w, "// Decode%[3]s 按 %[4]s 解出 %[5]s（C.14-R2）。\nfunc (v *%[1]s) Decode%[3]s() (any, error) {\n\tswitch v.%[2]s {\n", name, d, f, u.disc, u.field)
			for _, b := range u.branches {
				fmt.Fprintf(&w, "\tcase %q:\n\t\treturn DecodeAs[%s](v.%s)\n", b.value, b.typ, f)
			}
		}
		fmt.Fprintf(&w, "\tdefault:\n\t\treturn nil, fmt.Errorf(%q, v.%s)\n\t}\n}\n\n", name+"：不认识的 "+u.disc+" %q", d)
	}
	return w.String()
}
